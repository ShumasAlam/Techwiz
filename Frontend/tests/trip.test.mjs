import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import vm from 'node:vm'
import { catalogTypes, planForMarket, quantityLabel } from '../src/utils/trip.js'
const source = readFileSync(new URL('../src/api/mockData.js', import.meta.url), 'utf8').replace(/^import (\w+) from .+$/gm, 'const $1 = "demo-image.jpg"').replaceAll('export ', '')
const seed = vm.runInNewContext(source + '\ncloneSeedData()')
assert.equal(seed.products.length, 40)
for (const product of seed.products) {
  const farmer = seed.farmers.find((item) => item.id === product.farmerId)
  assert(farmer)
  assert(product.marketIds.every((id) => farmer.marketIds.includes(id) && seed.markets.some((market) => market.id === id)))
  assert(product.image && product.unit && product.rating >= 0 && product.price > 0)
}
const types = catalogTypes(seed)
for (const category of ['Vegetables', 'Fruits', 'Dairy', 'Eggs', 'Bakery', 'Other Produce']) assert(types.some((type) => type.category === category))
const list = ['tomatoes:kg', 'spinach:bunch', 'eggs:dozen', 'bread:loaf'].map((key) => ({ ...types.find((type) => type.key === key), quantity: key === 'eggs:dozen' ? 1 : 2 }))
const plan = planForMarket(seed, seed.markets[0], list)
assert.equal(plan.foundCount, 4)
assert.equal(plan.total, 2000)
assert.equal(plan.stops.length, 3)
assert.equal(quantityLabel(list[2]), '12 eggs (1 dozen)')
const partial = planForMarket(seed, seed.markets[0], [...list, { ...types.find((type) => type.key === 'cheese:pack'), quantity: 1 }])
assert.equal(partial.foundCount, 4)
assert.equal(partial.total, plan.total)
const overstock = planForMarket(seed, seed.markets[0], [{ ...list[0], quantity: 999 }])
assert.equal(overstock.foundCount, 0)
assert.equal(overstock.total, 0)
const storage = new Map()
const old = structuredClone(seed)
old.products = old.products.filter((product) => Number(product.id.slice(2)) < 30)
old.products[0].stock = 4
storage.set('marketlink_demo_db_v1', JSON.stringify(old))
const apiSource = readFileSync(new URL('../src/api/index.js', import.meta.url), 'utf8').replace(/^import .+$/gm, '').replace("import.meta.env.VITE_API_URL?.replace(/\\/$/, '')", 'undefined').replace('export const api', 'const api').replace('export default api', '')
const api = vm.runInNewContext(apiSource + '\napi', { cloneSeedData: () => structuredClone(seed), uid: () => 'test-' + Math.random(), localStorage: { getItem: (key) => storage.get(key), setItem: (key, value) => storage.set(key, value) }, window: { dispatchEvent() {} }, CustomEvent: class {}, setTimeout })
const migrated = api.snapshot()
assert.equal(migrated.products.length, 40)
assert.equal(migrated.products[0].stock, 4)
assert.equal(migrated.orders.length, old.orders.length)
const orders = await api.orders.createBatch({ customerId: 'u-customer', marketId: plan.market.id, pickupDate: '26 Sep 2026', pickupSlot: '10:00–10:30 AM', items: plan.picks.map((pick) => ({ productId: pick.product.id, quantity: pick.quantity })) })
assert.equal(orders.length, 3)
assert.equal(orders.reduce((sum, order) => sum + order.total, 0), plan.total)
for (const pick of plan.picks) assert.equal(api.snapshot().products.find((product) => product.id === pick.product.id).stock, pick.product.stock - pick.quantity)
await assert.rejects(() => api.orders.createBatch({ customerId: 'u-customer', marketId: 'm-1', pickupDate: '26 Sep 2026', pickupSlot: '10:00 AM', items: [{ productId: 'p-33', quantity: 1 }] }), /cannot be collected/)
console.log('PASS: catalog relationships, category coverage, quantities, totals, partial availability, stock limits, migration preservation, reservation grouping and stock updates')


// Dashboard persistence and session contracts, using an isolated demo store.
