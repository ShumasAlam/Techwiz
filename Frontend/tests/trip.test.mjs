const authSource = readFileSync(new URL('../src/context/AuthContext.jsx', import.meta.url), 'utf8')
const logoutBody = authSource.match(/const logout = \(\) => \{([\s\S]*?)\n  \}/)[1]
for (const role of ['customer', 'farmer', 'admin']) {
  storage.set('marketlink_session', JSON.stringify({ user: { role } }))
  storage.set('marketlink_token', 'demo-' + role)
  storage.set('marketlink_cart', 'preserved-basket')
  let currentUser = { role }; let destination = null
  vm.runInNewContext(logoutBody, { SESSION_KEY: 'marketlink_session', localStorage: { removeItem: (key) => storage.delete(key) }, setUser: (value) => { currentUser = value }, navigate: (path) => { destination = path } })
  assert.equal(currentUser, null); assert.equal(destination, '/')
  assert(!storage.has('marketlink_session')); assert(!storage.has('marketlink_token'))
  assert.equal(storage.get('marketlink_cart'), 'preserved-basket')
  const dashboard = readFileSync(new URL('../src/pages/' + role + '/' + role[0].toUpperCase() + role.slice(1) + 'Dashboard.jsx', import.meta.url), 'utf8')
  assert(dashboard.includes('onClick={logout}'))
}
console.log('PASS: market CRUD and validation, active-pickup deletion protection, preparing lifecycle, reviews/replies, favorites, shared logout for all 3 roles and basket preservation')

